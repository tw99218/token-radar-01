// The token radar's model (radar-2): one snapshot of the protocol universe in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and may add
// pre-token protocols below the watchlist floor: the early rows the radar exists to find. A protocol is
// pre-token when its index entry records no token (no market cap, no CoinGecko id, no symbol); the
// snapshot's live-token protocols are kept apart and shown as the market's own values, never mixed into
// the ranked board.
//
// Implied value follows only from the snapshot's own figures, never from a hardcoded list of names:
//
//   category multiple = median(mcap_usd / tvl_usd) over the live-token protocols of the same
//                         category (mcap > 0, tvl > 0); a category with fewer than 3 live comps,
//                         or a protocol with no category, falls back to the global median over all
//                         live-token protocols. The multiple is clamped to [0.05, 2.0].
//   base       = tvl_usd x category multiple
//   growth     = clamp(change_7d, -80, 150) per cent (null change counts as 0)
//   growthMult = 1 + (growth / 100) x 0.65
//   maturity   = 0.70 + 0.30 x log1p(min(age_days, 1095)) / log1p(1095)   (age unknown: 365 days)
//   breadth    = 1 + 0.04 x min(max(chains - 1, 0), 4), at most 1.16
//   implied    = max(1, round(base x growthMult x maturity x breadth))
//
// The multiples are computed from the snapshot at run time, so the same code scores any snapshot.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

